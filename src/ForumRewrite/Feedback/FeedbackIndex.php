<?php

declare(strict_types=1);

namespace ForumRewrite\Feedback;

/**
 * Renders docs/feedback/README.md from feedback items.
 */
final class FeedbackIndex
{
    private const KIND_HEADINGS = ['feature' => 'Features', 'bug' => 'Bugs', 'other' => 'Other'];
    private const OPEN_ORDER = ['in-progress', 'blocked', 'planned', 'ready', 'untriaged'];

    /**
     * @param list<FeedbackItem> $items
     */
    public static function render(array $items, bool $withHistory = false): string
    {
        $open = array_values(array_filter($items, static fn (FeedbackItem $item): bool => !$item->isClosed()));
        $closed = array_values(array_filter($items, static fn (FeedbackItem $item): bool => $item->isClosed()));

        $lines = [
            '# Feedback items',
            '',
            'Generated by `./v3 feedback index` from [`items/`](items/); do not edit. Format: [feedback item record](../specs/feedback_item_record_v1.md).',
            '',
            sprintf('%d open, %d closed.', count($open), count($closed)),
        ];
        if ($withHistory) {
            $lines[] = '';
            $lines[] = 'Where items came from and what is not yet folded in: [history](HISTORY.md).';
        }

        foreach (self::KIND_HEADINGS as $kind => $heading) {
            $kindItems = array_values(array_filter($open, static fn (FeedbackItem $item): bool => $item->header('Kind') === $kind));
            if ($kindItems === []) {
                continue;
            }
            usort($kindItems, static function (FeedbackItem $a, FeedbackItem $b): int {
                $order = array_search($a->header('Workflow'), self::OPEN_ORDER, true) <=> array_search($b->header('Workflow'), self::OPEN_ORDER, true);
                return $order !== 0 ? $order : strcmp($a->id(), $b->id());
            });
            array_push($lines, '', '## ' . $heading, '', '| Item | Title | Workflow | Evidence | Estimate | Sources |', '| --- | --- | --- | --- | --- | --- |');
            foreach ($kindItems as $item) {
                $lines[] = self::row($item, $item->header('Workflow'));
            }
        }

        if ($closed !== []) {
            usort($closed, static fn (FeedbackItem $a, FeedbackItem $b): int => strcmp($a->id(), $b->id()));
            array_push($lines, '', '## Closed', '', '| Item | Title | Outcome | Evidence | Estimate | Sources |', '| --- | --- | --- | --- | --- | --- |');
            foreach ($closed as $item) {
                $outcome = $item->header('Workflow');
                $target = $item->header('Duplicate-Of', $item->header('Superseded-By'));
                if ($target !== '') {
                    $outcome .= ' → [' . $target . '](items/' . $target . '.txt)';
                }
                $lines[] = self::row($item, $outcome);
            }
        }

        return implode("\n", $lines) . "\n";
    }

    /**
     * Writes the index next to the items folder; a partial file is never left behind.
     */
    public static function write(string $path, string $contents): void
    {
        $temporary = $path . '.tmp-' . getmypid();
        if (file_put_contents($temporary, $contents) === false || !rename($temporary, $path)) {
            @unlink($temporary);
            throw new \RuntimeException('Unable to write ' . $path);
        }
    }

    private static function row(FeedbackItem $item, string $workflow): string
    {
        $cells = [
            '[' . $item->id() . '](items/' . $item->id() . '.txt)',
            self::cell($item->header('Title')),
            $workflow,
            $item->header('Evidence', 'unknown'),
            $item->header('Estimate', '—'),
            (string) count($item->sources),
        ];
        return '| ' . implode(' | ', $cells) . ' |';
    }

    private static function cell(string $text): string
    {
        return str_replace('|', '\\|', $text);
    }
}
